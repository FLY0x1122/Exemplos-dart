void main() {
  // entrada
  int dia = 3;

  switch (dia) {
    case 1:
      print("Domingo");
    case 2:
      print("segunda");
    case 3:
      print("Terça");
    case 4:
      print("Quarta");
    case 5:
      print("Quinta");
    case 6:
      print("Sexta");
    case 7:
      print("Sabado");
    default:
      print("Dia inválido!");
  }
}
